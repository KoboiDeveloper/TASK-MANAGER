-- Gallery redesign: items (title groups) + multi-files + comments

IF OBJECT_ID('dbo.DT_PROJECT_GALLERY_ITEM', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.DT_PROJECT_GALLERY_ITEM (
    id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_DT_PROJECT_GALLERY_ITEM PRIMARY KEY DEFAULT NEWID(),
    projectId UNIQUEIDENTIFIER NOT NULL,
    viewId UNIQUEIDENTIFIER NULL,
    title NVARCHAR(200) NOT NULL,
    description NVARCHAR(1000) NULL,
    createdBy CHAR(8) NOT NULL,
    createdAt DATETIME2 NOT NULL CONSTRAINT DF_DT_PROJECT_GALLERY_ITEM_createdAt DEFAULT SYSUTCDATETIME(),
    updatedAt DATETIME2 NOT NULL CONSTRAINT DF_DT_PROJECT_GALLERY_ITEM_updatedAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_DT_PROJECT_GALLERY_ITEM_project FOREIGN KEY (projectId) REFERENCES dbo.DT_PROJECT(id) ON DELETE CASCADE,
    CONSTRAINT FK_DT_PROJECT_GALLERY_ITEM_uploader FOREIGN KEY (createdBy) REFERENCES dbo.DT_USER(nik)
  );
  CREATE INDEX IX_DT_PROJECT_GALLERY_ITEM_project_createdAt ON dbo.DT_PROJECT_GALLERY_ITEM(projectId, createdAt DESC);
  CREATE INDEX IX_DT_PROJECT_GALLERY_ITEM_createdBy ON dbo.DT_PROJECT_GALLERY_ITEM(createdBy);
END;

-- Add itemId + sortOrder to files if missing
IF COL_LENGTH('dbo.DT_PROJECT_GALLERY_FILE', 'itemId') IS NULL
BEGIN
  ALTER TABLE dbo.DT_PROJECT_GALLERY_FILE ADD itemId UNIQUEIDENTIFIER NULL;
END;

IF COL_LENGTH('dbo.DT_PROJECT_GALLERY_FILE', 'sortOrder') IS NULL
BEGIN
  ALTER TABLE dbo.DT_PROJECT_GALLERY_FILE ADD sortOrder INT NOT NULL CONSTRAINT DF_DT_PROJECT_GALLERY_FILE_sortOrder DEFAULT 0;
END;

-- Backfill: one item per orphan file
IF OBJECT_ID('dbo.DT_PROJECT_GALLERY_FILE', 'U') IS NOT NULL
BEGIN
  DECLARE @id UNIQUEIDENTIFIER, @projectId UNIQUEIDENTIFIER, @viewId UNIQUEIDENTIFIER, @filename NVARCHAR(255), @createdBy CHAR(8), @note NVARCHAR(500), @createdAt DATETIME2;

  DECLARE orphan_cursor CURSOR LOCAL FAST_FORWARD FOR
    SELECT id, projectId, viewId, filename, createdBy, note, createdAt
    FROM dbo.DT_PROJECT_GALLERY_FILE
    WHERE itemId IS NULL;

  OPEN orphan_cursor;
  FETCH NEXT FROM orphan_cursor INTO @id, @projectId, @viewId, @filename, @createdBy, @note, @createdAt;
  WHILE @@FETCH_STATUS = 0
  BEGIN
    DECLARE @itemId UNIQUEIDENTIFIER = NEWID();
    INSERT INTO dbo.DT_PROJECT_GALLERY_ITEM (id, projectId, viewId, title, description, createdBy, createdAt, updatedAt)
    VALUES (@itemId, @projectId, @viewId, LEFT(@filename, 200), @note, @createdBy, @createdAt, @createdAt);

    UPDATE dbo.DT_PROJECT_GALLERY_FILE SET itemId = @itemId, sortOrder = 0 WHERE id = @id;

    FETCH NEXT FROM orphan_cursor INTO @id, @projectId, @viewId, @filename, @createdBy, @note, @createdAt;
  END
  CLOSE orphan_cursor;
  DEALLOCATE orphan_cursor;
END;

-- FK for itemId (after backfill)
-- Drop project CASCADE on FILE to avoid multiple cascade paths (PROJECT→ITEM→FILE vs PROJECT→FILE)
IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_DT_PROJECT_GALLERY_FILE_project')
BEGIN
  ALTER TABLE dbo.DT_PROJECT_GALLERY_FILE DROP CONSTRAINT FK_DT_PROJECT_GALLERY_FILE_project;
END;

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_DT_PROJECT_GALLERY_FILE_item')
BEGIN
  DELETE FROM dbo.DT_PROJECT_GALLERY_FILE WHERE itemId IS NULL;

  ALTER TABLE dbo.DT_PROJECT_GALLERY_FILE ALTER COLUMN itemId UNIQUEIDENTIFIER NOT NULL;

  ALTER TABLE dbo.DT_PROJECT_GALLERY_FILE WITH CHECK
  ADD CONSTRAINT FK_DT_PROJECT_GALLERY_FILE_item
  FOREIGN KEY (itemId) REFERENCES dbo.DT_PROJECT_GALLERY_ITEM(id) ON DELETE CASCADE;

  CREATE INDEX IX_DT_PROJECT_GALLERY_FILE_itemId ON dbo.DT_PROJECT_GALLERY_FILE(itemId, sortOrder);
END;

-- Re-add project FK without cascade
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_DT_PROJECT_GALLERY_FILE_project')
BEGIN
  ALTER TABLE dbo.DT_PROJECT_GALLERY_FILE WITH CHECK
  ADD CONSTRAINT FK_DT_PROJECT_GALLERY_FILE_project
  FOREIGN KEY (projectId) REFERENCES dbo.DT_PROJECT(id) ON DELETE NO ACTION;
END;

