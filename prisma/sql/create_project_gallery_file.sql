-- Project gallery reference files (stored on Dropbox)

IF OBJECT_ID('dbo.DT_PROJECT_GALLERY_FILE', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.DT_PROJECT_GALLERY_FILE (
    id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_DT_PROJECT_GALLERY_FILE PRIMARY KEY DEFAULT NEWID(),
    projectId UNIQUEIDENTIFIER NOT NULL,
    viewId UNIQUEIDENTIFIER NULL,
    url NVARCHAR(500) NOT NULL,
    dropboxPath NVARCHAR(500) NOT NULL,
    filename NVARCHAR(255) NOT NULL,
    mimeType NVARCHAR(120) NOT NULL,
    bytes INT NOT NULL,
    createdBy CHAR(8) NOT NULL,
    createdAt DATETIME2 NOT NULL CONSTRAINT DF_DT_PROJECT_GALLERY_FILE_createdAt DEFAULT SYSUTCDATETIME(),
    note NVARCHAR(500) NULL,
    CONSTRAINT FK_DT_PROJECT_GALLERY_FILE_project FOREIGN KEY (projectId) REFERENCES dbo.DT_PROJECT(id) ON DELETE CASCADE,
    CONSTRAINT FK_DT_PROJECT_GALLERY_FILE_uploader FOREIGN KEY (createdBy) REFERENCES dbo.DT_USER(nik)
  );
  CREATE INDEX IX_DT_PROJECT_GALLERY_FILE_project_createdAt ON dbo.DT_PROJECT_GALLERY_FILE(projectId, createdAt);
  CREATE INDEX IX_DT_PROJECT_GALLERY_FILE_createdBy ON dbo.DT_PROJECT_GALLERY_FILE(createdBy);
END;
