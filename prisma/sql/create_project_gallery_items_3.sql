IF OBJECT_ID('dbo.DT_PROJECT_GALLERY_COMMENT', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.DT_PROJECT_GALLERY_COMMENT (
    id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_DT_PROJECT_GALLERY_COMMENT PRIMARY KEY DEFAULT NEWID(),
    itemId UNIQUEIDENTIFIER NOT NULL,
    authorNik CHAR(8) NOT NULL,
    body NVARCHAR(2000) NOT NULL,
    createdAt DATETIME2 NOT NULL CONSTRAINT DF_DT_PROJECT_GALLERY_COMMENT_createdAt DEFAULT SYSUTCDATETIME(),
    updatedAt DATETIME2 NOT NULL CONSTRAINT DF_DT_PROJECT_GALLERY_COMMENT_updatedAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_DT_PROJECT_GALLERY_COMMENT_item FOREIGN KEY (itemId) REFERENCES dbo.DT_PROJECT_GALLERY_ITEM(id) ON DELETE CASCADE,
    CONSTRAINT FK_DT_PROJECT_GALLERY_COMMENT_author FOREIGN KEY (authorNik) REFERENCES dbo.DT_USER(nik)
  );
  CREATE INDEX IX_DT_PROJECT_GALLERY_COMMENT_item_createdAt ON dbo.DT_PROJECT_GALLERY_COMMENT(itemId, createdAt);
  CREATE INDEX IX_DT_PROJECT_GALLERY_COMMENT_authorNik ON dbo.DT_PROJECT_GALLERY_COMMENT(authorNik);
END;

IF OBJECT_ID('dbo.DT_PROJECT_GALLERY_COMMENT_REACTION', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.DT_PROJECT_GALLERY_COMMENT_REACTION (
    id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_DT_PROJECT_GALLERY_COMMENT_REACTION PRIMARY KEY DEFAULT NEWID(),
    commentId UNIQUEIDENTIFIER NOT NULL,
    nik CHAR(8) NOT NULL,
    emoji NVARCHAR(16) NOT NULL,
    createdAt DATETIME2 NOT NULL CONSTRAINT DF_DT_PROJECT_GALLERY_COMMENT_REACTION_createdAt DEFAULT SYSUTCDATETIME(),
    updatedAt DATETIME2 NOT NULL CONSTRAINT DF_DT_PROJECT_GALLERY_COMMENT_REACTION_updatedAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_DT_PROJECT_GALLERY_COMMENT_REACTION_comment FOREIGN KEY (commentId) REFERENCES dbo.DT_PROJECT_GALLERY_COMMENT(id) ON DELETE CASCADE,
    CONSTRAINT FK_DT_PROJECT_GALLERY_COMMENT_REACTION_user FOREIGN KEY (nik) REFERENCES dbo.DT_USER(nik),
    CONSTRAINT UQ_DT_PROJECT_GALLERY_COMMENT_REACTION_comment_nik UNIQUE (commentId, nik)
  );
  CREATE INDEX IX_DT_PROJECT_GALLERY_COMMENT_REACTION_comment_emoji ON dbo.DT_PROJECT_GALLERY_COMMENT_REACTION(commentId, emoji);
  CREATE INDEX IX_DT_PROJECT_GALLERY_COMMENT_REACTION_nik ON dbo.DT_PROJECT_GALLERY_COMMENT_REACTION(nik);
END;
