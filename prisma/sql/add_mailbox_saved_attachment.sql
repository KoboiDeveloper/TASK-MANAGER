IF NOT EXISTS (
  SELECT 1 FROM sys.tables WHERE name = 'DT_MAILBOX_SAVED_ATTACHMENT'
)
BEGIN
  CREATE TABLE dbo.DT_MAILBOX_SAVED_ATTACHMENT (
    id VARCHAR(36) NOT NULL CONSTRAINT PK_DT_MAILBOX_SAVED_ATTACHMENT PRIMARY KEY,
    nik CHAR(8) NOT NULL,
    mailboxEmail NVARCHAR(255) NOT NULL,
    messageId NVARCHAR(255) NOT NULL,
    part NVARCHAR(64) NOT NULL,
    via VARCHAR(16) NOT NULL,
    url NVARCHAR(1000) NOT NULL,
    fileId NVARCHAR(255) NULL,
    filename NVARCHAR(500) NULL,
    updatedAt DATETIME2 NOT NULL CONSTRAINT DF_DT_MAILBOX_SAVED_ATTACHMENT_updatedAt DEFAULT SYSUTCDATETIME(),
    createdAt DATETIME2 NOT NULL CONSTRAINT DF_DT_MAILBOX_SAVED_ATTACHMENT_createdAt DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_DT_MAILBOX_SAVED_ATTACHMENT_USER FOREIGN KEY (nik) REFERENCES dbo.DT_USER(nik) ON DELETE CASCADE,
    CONSTRAINT UQ_DT_MAILBOX_SAVED_ATTACHMENT UNIQUE (nik, mailboxEmail, messageId, part, via)
  );
  CREATE INDEX IX_DT_MAILBOX_SAVED_ATTACHMENT_msg
    ON dbo.DT_MAILBOX_SAVED_ATTACHMENT (nik, mailboxEmail, messageId);
END;
